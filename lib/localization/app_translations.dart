  static String translate(String key, String locale) {
    final Map<String, String>? targetDict = translations[locale];
    final Map<String, String>? enDict = translations["en"];

    // 1. Direct match in active locale dictionary (e.g. 'en' or 'hi')
    if (targetDict != null && targetDict.containsKey(key)) {
      return targetDict[key]!;
    }

    // 2. Direct match fallback in 'en' dictionary if active locale is not 'en'
    if (locale != 'en' && enDict != null && enDict.containsKey(key)) {
      return enDict[key]!;
    }

    // 3. Case and whitespace insensitive match in active locale dictionary
    final cleanKey = _sanitize(key);
    if (targetDict != null) {
      for (final entry in targetDict.entries) {
        if (_sanitize(entry.key) == cleanKey) {
          return entry.value;
        }
      }
    }

    // 4. Case and whitespace insensitive match in 'en' fallback
    if (locale != 'en' && enDict != null) {
      for (final entry in enDict.entries) {
        if (_sanitize(entry.key) == cleanKey) {
          return entry.value;
        }
      }
    }

    // 5. If no translation dictionary entry exists, return original key string
    return key;
